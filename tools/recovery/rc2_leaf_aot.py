#!/usr/bin/env python3
"""Fail-closed build-time pilot for two recovered RC2 Aranos leaf services.

This is not a general MIPS translator. Only two complete, exact four-instruction
bodies are accepted. Input/output can contain original code: keep them private.
Generated Rust has fixed native control flow, no instruction dispatch and no
runtime dependency on an executable. Never infer compatibility from this pilot.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

# Review gates, not a disassembler/opcode executor. An instruction mutation must
# be investigated, never automatically accepted as an equivalent implementation.
SIGNATURES = {
    0x2F51A0: 'a01246b52b3a39ef2b3118b38f645c7958c1895ce786f8454f9eb25aa6d9c31d',
    0x368560: '829b0bd3375ff42f005f6d6961c2166c2d2f80eafddcdf69a46697e834a64d9d',
}


def initialized_elf_sections(blob):
    """Read ELF32 little-endian PROGBITS; never substitute BSS zeroes for code."""
    if len(blob) < 52 or blob[:7] != b'\x7fELF\x01\x01\x01':
        raise ValueError('expected ELF32 little-endian input')
    if struct.unpack_from('<H', blob, 18)[0] != 8:
        raise ValueError('expected MIPS ELF')
    off = struct.unpack_from('<I', blob, 32)[0]
    stride, count = struct.unpack_from('<HH', blob, 46)
    if stride < 40 or not count or off + stride * count > len(blob):
        raise ValueError('invalid ELF section headers')
    sections = []
    for i in range(count):
        kind, flags, address, fileoff, size = struct.unpack_from('<5I', blob, off + i * stride + 4)
        if kind != 1 or not address or not size:
            continue
        if fileoff + size > len(blob) or address + size > 0x2000000:
            raise ValueError('invalid initialized section extent')
        if any(address < a + len(data) and a < address + size for a, data in sections):
            raise ValueError('overlapping initialized sections')
        sections.append((address, blob[fileoff:fileoff + size]))
    return sections


def verify(sections):
    records = []
    for address, expected in SIGNATURES.items():
        matches = [data[address - base:address - base + 16]
                   for base, data in sections if base <= address and address + 16 <= base + len(data)]
        if len(matches) != 1 or hashlib.sha256(matches[0]).hexdigest() != expected:
            raise ValueError(f'unsupported original leaf signature at {address:08x}')
        records.append({'address': f'{address:08x}', 'original_bytes_sha256': hashlib.sha256(matches[0]).hexdigest(),
                        'instruction_count': 4, 'includes_return_delay_slot': True})
    return records


def rust_source():
    # The checked ABI explicitly exposes the scratch outputs changed by these
    # leaves. Registers not listed, caller arguments and floating-point state
    # are preserved by construction. Invalid mappings are errors, never success.
    return '''// Generated by rc2_leaf_aot.py after exact original signature verification.
// Experimental differential pilot only; not connected to the application.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct LeafScratch { pub v0: u64, pub v1: u64 }
#[derive(Debug, PartialEq)]
pub struct LeafMemoryError;
pub trait LeafMemory {
    fn read_u8(&self, address: u32) -> Result<u8, LeafMemoryError>;
    fn write_u16_le(&mut self, address: u32, value: u16) -> Result<(), LeafMemoryError>;
}
pub fn query_2f51a0(memory: &impl LeafMemory, scratch: &mut LeafScratch) -> Result<(), LeafMemoryError> {
    scratch.v0 = 0x001a0000;
    scratch.v0 = memory.read_u8(0x001a7a12)? as u64;
    scratch.v0 = u64::from(scratch.v0 != 0);
    Ok(())
}
pub fn store_368560(memory: &mut impl LeafMemory, scratch: &mut LeafScratch) -> Result<(), LeafMemoryError> {
    scratch.v1 = 0x00150000;
    scratch.v0 = 1;
    memory.write_u16_le(0x00152c26, 1)
}
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--elf', type=Path, required=True)
    ap.add_argument('--output-rust', type=Path, required=True)
    ap.add_argument('--report', type=Path, required=True)
    args = ap.parse_args()
    blob = args.elf.read_bytes()
    leaves = verify(initialized_elf_sections(blob))
    source = rust_source().encode()
    # No output is produced until all input signatures pass.
    args.output_rust.write_bytes(source)
    args.report.write_text(json.dumps({
        'schema': 1, 'status': 'EXACT_SIGNATURE_VERIFIED_AOT_PILOT_NOT_RUNTIME_INTEGRATED',
        'classification': 'GAME_SPECIFIC', 'reuse_decision': 'SELECTIVE_AOT_TRANSLATION_CANDIDATE',
        'elf_sha256': hashlib.sha256(blob).hexdigest(),
        'generated_rust_sha256': hashlib.sha256(source).hexdigest(), 'leaves': leaves,
        'memory_bindings': [{'address': '001a7a12', 'width': 1, 'effect': 'read'},
                            {'address': '00152c26', 'width': 2, 'effect': 'write_one_little_endian'}],
        'native_service_calls': [], 'rng_draws': 0, 'floating_point': 'NOT_EXERCISED',
        'branch_delay_slots': 'BOTH_INCLUDED', 'original_execution_trace': 'NOT_AVAILABLE',
        'limitations': ['Only these exact leaves; no general translation coverage',
                        'No host/PS2 floating-point or native-service-call ABI validation',
                        'No GPU, iOS or physical device execution proved by generation'],
    }, indent=2) + '\n')


if __name__ == '__main__':
    main()
